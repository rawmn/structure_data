#pragma once
#include "Stack.h"

//! \brief Структура очереди на двух стеках.
struct QueueTwoStack
{
private:
    //! \brief Основной стек, в который будут добавляться элементы.
    Stack* _inStack;

    //! \brief Второстепенный стек, из которого будут возвращаться элементы.
    Stack* _outStack;

public:
    //! \brief Создает структуру данных очереди на двух стеках.
    QueueTwoStack();

    //! \brief Освобождает память.
    ~QueueTwoStack();

    //! \brief Очищает очередь.
    void ClearQueue();

    //! \brief Добавляет элемент в очередь.
    //! \param data Вносимые данные.
    void Enqueue(int data);

    //! \brief Достает элемент из очереди.
    //! \return Элемент из очереди.
    //! \throws std::underflow_error если очередь пуста.
    int Dequeue();

    //! \brief Изменение размера. Стеки построены на связном списке и растут
    //! динамически, поэтому физическое изменение размера не требуется.
    //! \return Всегда false (размер не менялся).
    bool Resize();

    //! \brief Возвращает первый элемент очереди, не удаляя его и не меняя
    //! распределение элементов между стеками.
    //! \throws std::underflow_error если очередь пуста.
    int Peek();

    //! \brief Возвращает количество элементов во входном стеке.
    int GetInSize();

    //! \brief Возвращает количество элементов в выходном стеке.
    int GetOutSize();

    //! \brief Возвращает общее количество элементов в очереди.
    int GetSize();
};
