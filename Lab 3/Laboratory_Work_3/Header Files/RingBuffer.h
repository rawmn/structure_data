#pragma once

//! \brief Структура кольцевой буфер.
struct RingBuffer
{
private:
    //! \brief Массив кольцевого буфера.
    int* _array;

    //! \brief Индекс конца кольцевого буфера.
    int _tailIndex = -1;

    //! \brief Индекс начала кольцевого буфера.
    int _headIndex = -1;

    //! \brief Вместимость кольцевого буфера.
    int _capacity;

    //! \brief Размер кольцевого буфера.
    int _size = 0;

public:
    //! \brief Создает структуру кольцевой буфер.
    RingBuffer();

    //! \brief Освобождает память.
    ~RingBuffer();

    //! \brief Добавляет данные в кольцевой буфер.
    //! Если буфер заполнен, вместимость автоматически увеличивается (Resize),
    //! поэтому данные не теряются.
    //! \param data Данные.
    void AddElement(int data);

    //! \brief Достает первый элемент из кольцевого буфера. После чего удаляет этот
    //! элемент из буфера.
    //! \return Значение первого элемента.
    //! \throws std::underflow_error если буфер пуст.
    int GetElement();

    //! \brief Возвращает первый элемент, не удаляя его.
    //! \return Значение первого элемента.
    //! \throws std::underflow_error если буфер пуст.
    int PeekElement();

    //! \brief Увеличивает размер массива кольцевого буфера (в 2 раза).
    void Resize();

    //! \brief Очищает кольцевой буфер.
    void ClearRingBuf();

    //! \brief Возвращает массив кольцевого буфера,
    //! где первый элемент находится под индексом _headIndex,
    //! а последний под индексом _tailIndex.
    //! \return Массив кольцевого буфера.
    int* GetArray();

    //! \brief Возвращает значение свободного места в кольцевом буфере.
    //! \return Количество свободного места в кольцевом буфере.
    int GetFreeSpace();

    //! \brief Возвращает количество элементов в кольцевом буфере.
    //! \return Количество элементов в кольцевом буфере.
    int GetSize();

    //! \brief Возвращает вместимость буфера.
    int GetCapacity();

    //! \brief Возвращает индекс начала буфера (-1, если пуст).
    int GetHeadIndex();

    //! \brief Возвращает индекс конца буфера (-1, если пуст).
    int GetTailIndex();
};
